//go:build ignore

// Генерирует codes.go из _errors.md официального репозитория документации:
//
//	go run errors/gen_codes.go -rev <commit> <path/to/md/_errors.md> > errors/codes.go
package main

import (
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"html"
	"log"
	"os"
	"regexp"
	"strings"
)

var row = regexp.MustCompile(`(?m)^\|\s*<div id="error_(\d+)">(\d+)</div>\s*\|([^|]*)\|`)

func main() {
	rev := flag.String("rev", "", "commit api-remap-1.2-doc")
	flag.Parse()
	if *rev == "" || flag.NArg() != 1 {
		log.Fatal("usage: gen_codes -rev <commit> <_errors.md>")
	}
	data, err := os.ReadFile(flag.Arg(0))
	if err != nil {
		log.Fatal(err)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen_codes.go; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package errors\n\n")
	fmt.Fprintf(&b, "// Источник: https://github.com/moysklad/api-remap-1.2-doc/blob/%s/md/_errors.md\n", *rev)
	fmt.Fprintf(&b, "// SHA-256 источника: %x\n", sha256.Sum256(data))
	b.WriteString("// Комментарий — сообщение из источника; классифицировать ошибки нужно по коду, а не по тексту.\n")
	b.WriteString("const (\n")
	seen := map[string]bool{}
	for _, m := range row.FindAllStringSubmatch(string(data), -1) {
		if m[1] != m[2] {
			log.Fatalf("anchor %s != code %s", m[1], m[2])
		}
		if seen[m[1]] {
			log.Fatalf("duplicate code %s", m[1])
		}
		seen[m[1]] = true
		fmt.Fprintf(&b, "\tCode%s = %s // %s\n", m[1], m[1], strings.Join(strings.Fields(html.UnescapeString(m[3])), " "))
	}
	b.WriteString(")\n")
	if len(seen) == 0 {
		log.Fatal("no codes found")
	}

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	os.Stdout.Write(src)
}
