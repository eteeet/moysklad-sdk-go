package moysklad

import (
	"context"
	"time"
)

// Limiter — ограничитель запросов аккаунта: темп и параллельность. Реализацию подставляет потребитель,
// например коннектор с бюджетом на каждый аккаунт. Через него проходит каждая попытка, включая повторы.
type Limiter interface {
	// Acquire ждёт разрешения на запрос. release вызывается, когда ответ прочитан.
	// Ошибка отменяет запрос и возвращается вызывающему.
	Acquire(ctx context.Context) (release func(), err error)
	// Backoff сообщает, что МойСклад ответил 429 и просит подождать d. С ограничителем SDK сам
	// не ждёт: паузу выдерживает Acquire, и она задерживает все запросы аккаунта, а не один.
	Backoff(d time.Duration)
}
